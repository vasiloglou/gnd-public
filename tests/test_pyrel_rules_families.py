"""PL13a: the remaining constraint families as PyRel requirements, agreeing with GND's checker.

The corpus in tests/fixtures/pyrel-rules-families/ holds GND's own verdicts (expected.json,
generated by gnd.api.check). Every DuckDB rules program must reproduce them: the same status,
witness and exit code. One documented normalisation: for value constraints GND lists one
offending value per fact, in population order, and the program lists each distinct value once,
so they are compared as sets.

The acyclic witness is compared exactly: GND's cycle is deterministic (a depth-first search from
the smallest node, successors in population order), and the program reproduces it.

review/ holds the independent review's reproductions, compared live with gnd.api.check.
"""
from __future__ import annotations

import json
import subprocess
from pathlib import Path

import pytest

from gnd import api
from gnd.export.pyrel_rules import render
from gnd.export.pyrel_runtime import ExportInputError, _parse_document

ROOT = Path(__file__).resolve().parents[1]
NATIVE = ROOT / 'tutorials/runtimes/.venv/bin/python'
CORPUS = ROOT / 'tests/fixtures/pyrel-rules-families'
REVIEW = CORPUS / 'review'
EXPECTED = json.loads((CORPUS / 'expected.json').read_text())['results']
CASES = sorted((name, row) for name, row in EXPECTED.items() if not row['model'].startswith('exclusive-or-multi'))


def _program(tmp_path_factory, model):
    path = tmp_path_factory.getbasetemp() / f'{Path(model).stem}.py'
    if not path.exists():
        path.write_text(render(CORPUS / model, 'duckdb'))
    return path


def _lines(stdout):
    """{constraint id: [(status, witness or None), ...]} from the program's report lines."""
    found = {}
    for line in stdout.splitlines():
        name, status, *rest = line.split('  ')
        witness = json.loads(rest[0]) if rest and status in ('violated', 'warning') else None
        found.setdefault(name, []).append((status, witness))
    return found


def _ids(doc):
    """GND's constraint_ref -> constraint id, as expected.json maps them."""
    ids = {f'constraints[{i}]': c['id'] for i, c in enumerate(doc.get('constraints', []))}
    for fact in doc['fact_types']:
        for j, c in enumerate(fact.get('constraints') or []):
            ids[f"fact_types[{fact['id']}].constraints[{j}]"] = c.get('id') or f"{fact['id']}#{j}"
    return ids


_PER_LINE = ('value', 'guarded', 'mandatory')


def _assert_agrees(stdout, verdicts):
    """Every GND verdict matches the program's line(s) for that rule; every other rule prints OK."""
    ours = _lines(stdout)
    for cid, verdict in verdicts:
        want = {'pass': 'OK', 'fail': 'violated', 'warning': 'warning', 'vacuous': 'vacuous',
                'unchecked': 'not checked'}[verdict['verdict']]
        lines = ours.pop(cid)
        assert {status for status, _ in lines} == {want}, (cid, lines, verdict['verdict'])
        if want not in ('violated', 'warning'):
            continue
        if verdict['constraint_type'] in _PER_LINE:
            # One line per witness. GND lists one value per offending fact (value), bindings in its own
            # order (guarded), or bare values (mandatory, where each line is [value]); compared as sets,
            # as tests/test_pyrel_rules.py does for these families.
            flat = verdict['constraint_type'] == 'mandatory'
            ours_set = {json.dumps(w[0] if flat else w, sort_keys=True) for _, w in lines}
            assert ours_set == {json.dumps(v, sort_keys=True) for v in verdict['offending_facts']}, (cid, lines)
        else:
            assert lines == [(want, verdict['offending_facts'])], (cid, lines, verdict['offending_facts'])
    assert all(lines == [('OK', None)] for lines in ours.values()), ours


@pytest.mark.pyrel_oracle
@pytest.mark.parametrize('name,row', CASES, ids=[name for name, _ in CASES])
def test_duckdb_program_agrees_with_gnd_on_every_family(tmp_path_factory, name, row):
    program = _program(tmp_path_factory, row['model'])
    run = subprocess.run([str(NATIVE), '-I', str(program), str(CORPUS / row['population'])],
                         capture_output=True, text=True, timeout=300, check=False)
    assert run.stderr == '', run.stderr
    assert run.returncode == row['exit_code'], run.stdout
    _assert_agrees(run.stdout, [(v['id'], v) for v in row['verdicts']])


@pytest.mark.parametrize('model,reason', [
    (CORPUS / 'exclusive-or-multi.orm.json', 'multi-role sequences'),
    (REVIEW / 'refuse-external-uniqueness.orm.json', 'external uniqueness'),
    (REVIEW / 'refuse-external-frequency.orm.json', 'external frequency'),
    (REVIEW / 'helper-collision.orm.json', "fact type 'likes_reverse' has the name of a relation"),
])
def test_unsupported_constructs_are_refused_by_name(model, reason):
    with pytest.raises(ExportInputError, match=reason):
        render(model, 'duckdb')


REVIEW_CASES = [
    ('ring-integer', 'p1'),            # F1 numeric order, F4 exact cycle
    ('frequency-integer', 'p1'),       # F1
    ('inclusive-or-integer', 'p2'),    # F1
    ('value-roster', 'p2'),            # F2 a roster-only violation is not vacuous
    ('value-roster-pass', 'p4'),       # F2 a roster-only pass exits 0
    ('textual', 'p1'),                 # F6 textual rules are listed as not checked (exit 4)
    ('textual-with-exclusion', 'fail'),
    ('textual-with-exclusion', 'vacuous'),
]


@pytest.mark.pyrel_oracle
@pytest.mark.parametrize('name,case', REVIEW_CASES, ids=[f'{n}-{c}' for n, c in REVIEW_CASES])
def test_review_reproductions_agree_with_gnd_exactly(tmp_path, name, case):
    model, population = REVIEW / f'{name}.orm.json', REVIEW / f'{name}.{case}.population.json'
    gnd = api.check(str(model), str(population), unredacted=True)
    program = tmp_path / 'rules.py'
    program.write_text(render(model, 'duckdb'))
    run = subprocess.run([str(NATIVE), '-I', str(program), str(population)],
                         capture_output=True, text=True, timeout=300, check=False)
    assert run.stderr == '', run.stderr
    assert run.returncode == gnd['exit_code'], run.stdout
    ids = _ids(_parse_document(model.read_text()))
    _assert_agrees(run.stdout, [(ids[v['constraint_ref']], v) for v in gnd['verdicts']])


@pytest.mark.pyrel_oracle
@pytest.mark.parametrize('model', sorted(p.name for p in CORPUS.glob('*.orm.json') if 'multi' not in p.name))
def test_lqp_program_compiles_every_requirement(tmp_path, model):
    program = tmp_path / 'rules_lqp.py'
    program.write_text(render(CORPUS / model, 'lqp'))
    run = subprocess.run([str(NATIVE), '-I', str(program), '--compile'], capture_output=True, text=True,
                         timeout=300, check=False)
    assert run.returncode == 0, run.stdout + run.stderr
    assert run.stdout.splitlines()[0].startswith(f'{LQP_REQUIRES[model]} requirements compiled'), run.stdout


