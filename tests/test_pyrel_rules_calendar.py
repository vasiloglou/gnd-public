def _dispatch_copy(tmp_path):
    folder = tmp_path / 'dispatch'
    shutil.copytree(EXAMPLES / 'dispatch', folder)
    return folder


def test_a_tampered_reference_is_refused_at_export(tmp_path):
    folder = _dispatch_copy(tmp_path)
    catalog = folder / 'references/catalog.pop.json'
    catalog.write_text(catalog.read_text() + '\n')   # one extra byte changes the SHA-256
    with pytest.raises(ExportInputError, match='reference raw hash does not match'):
        render(folder / 'model.orm.json', 'duckdb')


def test_a_missing_reference_is_refused_at_export(tmp_path):
    folder = _dispatch_copy(tmp_path)
    (folder / 'references/catalog.pop.json').unlink()
    with pytest.raises(ExportInputError, match='reference population'):
        render(folder / 'model.orm.json', 'duckdb')


@pytest.mark.pyrel_oracle
def test_a_candidate_naming_a_reference_owned_fact_type_is_refused(tmp_path):
    folder = _dispatch_copy(tmp_path)
    population = json.loads((folder / 'seed.pop.json').read_text())
    population['facts']['dispatch_allowed'] = []
    path = folder / 'owned.pop.json'
    path.write_text(json.dumps(population))
