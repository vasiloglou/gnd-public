"""Generate the ILP learners' comparison table from the committed live-run evidence (IL6).

Each row is one invocation of one adapter: what the learner did, what it
proposed, and what GND's import did with it. The rows come from each run's
``outcome.json``, its retained learner output and its retained import result;
nothing is run but GND's own readers and, for AMIE, GND's own count of which
mined rules hold. The table is written to
``tests/fixtures/ilp_learners/il6/comparison.json`` and between the markers in
``docs/reference/ilp-bridge.md`` "Comparing the learners".

Usage, from the repository root::

    uv run python tools/ilp_comparison.py           # check: exit 1 if either differs
    uv run python tools/ilp_comparison.py --write   # rewrite the bridge section

The golden is the phase's corpus (IL6-D11): it was committed before this tool
and the tool never writes it.

Spec: ``.gnd-planning/milestones/ilp-learners/notes/phase-IL6-spec.md`` §6.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

SCHEMA_VERSION = "gnd-ilp-comparison/1"
START = "<!-- ilp-comparison:start (generated by tools/ilp_comparison.py; do not edit) -->"
END = "<!-- ilp-comparison:end -->"
EVIDENCE = ".gnd-planning/milestones/ilp-learners/evidence"
GOLDEN = "tests/fixtures/ilp_learners/il6/comparison.json"
BRIDGE = "docs/reference/ilp-bridge.md"
STAFFING = "tests/fixtures/ilp_learners/il4"
#: (adapter, invocation, evidence directory, learner output file), in plan order.
LABELLED = (
    ("popper", 1, "IL1/live/invocation-1", "program.pl"),
    ("popper", 2, "IL1/live/invocation-2", "program.pl"),
    ("popper", 3, "IL1/live/invocation-3", "program.pl"),
    ("ilasp", 1, "IL2/live/invocation-1", "hypothesis.las"),
    ("llm", 1, "IL5/live/invocation-1", "answer.json"),
    ("rules", 1, "IL3/live/invocation-1", "ruleset.txt"),
)
UNLABELLED = (
    ("amie", 1, "IL4/live/invocation-1"),
    ("amie", 2, "IL4/live/invocation-2"),
)
#: A note a phase record adds to a row's reproducibility (IL6-D5 (o)).
NOTES = {("rules", 1): "; repeated runs pick other thresholds (IL3-F5)"}
_REFUSAL = re.compile(r"(?:clause|rule) (\d+): ([a-z]+(?:-[a-z]+)*): ")


def _json(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


def _learner(outcome: dict[str, Any]) -> dict[str, str]:
    """The learner as the run recorded it: top level, or under the adapter's own key."""
    for record in (outcome, outcome.get("popper"), outcome.get("ilasp"), outcome.get("agent")):
        if isinstance(record, dict) and "learner" in record:
            return dict(record["learner"])
    raise ValueError("outcome.json names no learner")


def _first_refusal(live: Path) -> dict[str, Any] | None:
    stderr = live / "import-stderr.txt"
    if not stderr.exists():
        return None
    match = _REFUSAL.match(stderr.read_text(encoding="utf-8"))
    return {"name": match.group(2), "index": int(match.group(1))} if match else None


def _admitted(live: Path, exit_code: int | None) -> int | None:
    if exit_code is None:
        return None
    return len(_json(live / "proposal.json")["operations"]) if exit_code == 0 else 0


def _common(adapter: str, invocation: int, outcome: dict[str, Any], source: str) -> dict[str, Any]:
    return {"adapter": adapter, "learner": _learner(outcome), "input": source, "invocation": invocation,
            "run_of_record": outcome["run_of_record"], "termination": outcome["termination"],
            "import": outcome["import"], "import_exit": outcome.get("import_exit"),
            "reproducibility": outcome["reproducibility"] + NOTES.get((adapter, invocation), "")}


def _proposed(adapter: str, text: str) -> int | None:
    """The clauses in the learner's output as the target's own reader parses them."""
    from gnd.export.ilp_learners import learner

    if not text.strip():
        return None
    parse = learner(adapter).parse
    return len(parse(text)["clauses"] if parse else json.loads(text)["clauses"])


def labelled_row(root: Path, adapter: str, invocation: int, directory: str, output: str) -> dict[str, Any]:
    live = root / EVIDENCE / directory
    outcome = _json(live / "outcome.json")
    row = _common(adapter, invocation, outcome, "refunds")
    path = live / output
    proposed = _proposed(adapter, path.read_text(encoding="utf-8")) if path.exists() else None
    refusal = _first_refusal(live)
    if row["import_exit"] is None:
        not_evaluated = None
    elif refusal is None:
        not_evaluated = 0
    else:
        not_evaluated = proposed - refusal["index"] - 1
    return {**row, "clauses_proposed": proposed, "first_refusal": refusal,
            "clauses_not_evaluated": not_evaluated, "clauses_admitted": _admitted(live, row["import_exit"])}


def hold(root: Path, text: str) -> int:
    """GND's count of the mined rules that hold on the staffing population (every head pair)."""
    from gnd.export import ilp, ilp_amie
    from gnd.export.ilp_service import _mined_inputs
    from gnd.redaction import RedactionPolicy

    inputs = _mined_inputs(root / STAFFING / "model.orm.yaml", root / STAFFING / "population.yaml")
    relations, uncovered, _skipped = ilp_amie.relation_table(inputs.model, list(inputs.population.covers))
    shape, _columns = ilp.schema(inputs.model, RedactionPolicy.from_model(inputs.model).effective_roles)
    closures = ilp.type_closures(inputs.model)
    facts = ilp_amie.pairs(relations, inputs.population)
    held = 0
    for index, rule in enumerate(ilp_amie.parse_rules(text)):
        try:
            counted = ilp_amie.count(ilp_amie.mapped(rule, index, relations, uncovered, shape, closures),
                                     facts, index)
        except ilp.IlpError:
            continue
        held += counted.denominator > 0 and counted.numerator == counted.denominator
    return held


def unlabelled_row(root: Path, adapter: str, invocation: int, directory: str) -> dict[str, Any]:
    from gnd.export import ilp_amie

    live = root / EVIDENCE / directory
    outcome = _json(live / "outcome.json")
    row = _common(adapter, invocation, outcome, "staffing")
    path = live / "rules.txt"
    text = path.read_text(encoding="utf-8") if path.exists() else ""
    return {**row, "rules_mined": len(ilp_amie.parse_rules(text)) if text else None,
            "rules_hold": hold(root, text) if text else None,
            "rules_admitted": _admitted(live, row["import_exit"]), "first_refusal": _first_refusal(live)}


def build(root: Path) -> dict[str, Any]:
    return {"schema_version": SCHEMA_VERSION,
            "labelled": [labelled_row(root, *entry) for entry in LABELLED],
            "unlabelled": [unlabelled_row(root, *entry) for entry in UNLABELLED]}


def _cell(value: Any) -> str:
    return "—" if value is None else str(value)


def _refusal(value: dict[str, Any] | None, unit: str) -> str:
    return "—" if value is None else f"`{value['name']}`, {unit} {value['index']}"


def _head(row: dict[str, Any]) -> str:
    name, version = row["learner"]["name"], row["learner"]["version"]
    learner = f"{name}, version not reported" if version == "unreported" else f"{name} {version}"
    record = "yes" if row["run_of_record"] else "no (ruled)"
    return f"| {row['adapter']} ({learner}) | {row['invocation']} | {record} | `{row['termination']}` / `{row['import']}`"


def markdown(doc: dict[str, Any]) -> str:
    """The two tables, labelled then unlabelled, as the bridge page shows them."""
    lines = [
        "**Labelled learners, on the refunds example.**",
        "",
        ("| Adapter (learner) | Inv. | Run of record | Outcome | Clauses proposed | Import exit "
        "| First refusal | Not evaluated | Admitted |"),
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for row in doc["labelled"]:
        lines.append(f"{_head(row)} | {_cell(row['clauses_proposed'])} | {_cell(row['import_exit'])} "
                     f"| {_refusal(row['first_refusal'], 'clause')} | {_cell(row['clauses_not_evaluated'])} "
                     f"| {_cell(row['clauses_admitted'])} |")
    lines += [
        "",
        "**The rule miner, on the staffing population.**",
        "",
        ("| Adapter (learner) | Inv. | Run of record | Outcome | Rules mined | Hold (GND's count) "
        "| Import exit | First refusal | Admitted |"),
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for row in doc["unlabelled"]:
        lines.append(f"{_head(row)} | {_cell(row['rules_mined'])} | {_cell(row['rules_hold'])} "
                     f"| {_cell(row['import_exit'])} | {_refusal(row['first_refusal'], 'rule')} "
                     f"| {_cell(row['rules_admitted'])} |")
    notes = sorted({row["reproducibility"] for row in doc["labelled"] + doc["unlabelled"]})
    lines += ["", "Every row is a single run. Reproducibility, as each run recorded it: "
              + "; ".join(f"\"{note}\"" for note in notes) + "."]
    return "\n".join(lines)


def _golden_bytes(doc: dict[str, Any]) -> str:
    return json.dumps(doc, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def _bridge(text: str, doc: dict[str, Any]) -> str:
    start, end = text.index(START), text.index(END)
    return text[:start + len(START)] + "\n" + markdown(doc) + "\n" + text[end:]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--write", action="store_true", help="rewrite the bridge section")
    args = parser.parse_args()
    doc = build(args.root)
    golden, bridge = args.root / GOLDEN, args.root / BRIDGE
    wanted = {golden: _golden_bytes(doc), bridge: _bridge(bridge.read_text(encoding="utf-8"), doc)}
    stale = [path for path, text in wanted.items() if path.read_text(encoding="utf-8") != text]
    if args.write and bridge in stale:
        bridge.write_text(wanted[bridge], encoding="utf-8")
        stale.remove(bridge)
    for path in stale:
        print(f"{path.relative_to(args.root)} differs from the generated table", file=sys.stderr)
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
