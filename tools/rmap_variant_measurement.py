"""OB2-C5: compare the two Rmap variants over the export census and the corpus (D5 input).

Usage: uv run python tools/rmap_variant_measurement.py OUT.md
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from gnd.model import load_model
from gnd.rmap import RmapVariant, dispositions, map_model

ROOT = Path(__file__).resolve().parents[1]
CENSUS = ROOT / ".gnd-planning/milestones/ossie-interchange/evidence/OS0/revised/census.txt"
CORPUS = ROOT / "tests/fixtures/rmap"


def _metrics(schema):
    return {
        "tables": len(schema.tables),
        "unmapped_fact_types": sum(1 for u in schema.unmapped if u.kind == "fact_type"),
        "foreign_keys": sum(len(t.foreign_keys) for t in schema.tables),
        "nullable_columns": sum(1 for t in schema.tables for c in t.columns if c.nullable),
    }


def _agrees(case: Path, variant: RmapVariant, schema, model) -> str:
    number = case.name[:2]
    answer = CORPUS / "answers" / (f"{number}.alternate.json" if variant is RmapVariant.ALTERNATE else f"{number}.json")
    if not answer.exists():
        answer = CORPUS / "answers" / f"{number}.json"
    expected = json.loads(answer.read_text())
    tables = [t.name for t in schema.tables]
    return "yes" if tables == [t["name"] for t in expected["tables"]] and len(dispositions(model, schema)) == len(expected["dispositions"]) else "no"


def rows() -> list[dict]:
    sources = [("census", ROOT / line) for line in CENSUS.read_text().splitlines()]
    sources += [("corpus", path / "model.yaml") for path in sorted((CORPUS / "cases").iterdir()) if path.is_dir()]
    result = []
    for origin, path in sources:
        try:
            model = load_model(path)
        except Exception as error:  # noqa: BLE001 -- include-bearing census models are refused by the loader route
            result.append({"model": str(path.relative_to(ROOT)), "origin": origin, "skipped": type(error).__name__})
            continue
        row = {"model": str(path.relative_to(ROOT)), "origin": origin}
        for variant in RmapVariant:
            schema = map_model(model, variant=variant)
            row[variant.name] = _metrics(schema)
            if origin == "corpus":
                row[variant.name]["agrees"] = _agrees(path.parent, variant, schema, model)
        result.append(row)
    return result


def render(data: list[dict]) -> str:
    keys = ["tables", "unmapped_fact_types", "foreign_keys", "nullable_columns"]
    lines = [
        "# OB2 variant measurement (OB2-C5, input to D5)",
        "",
        "Generated by `uv run python tools/rmap_variant_measurement.py`. Each cell is HALPIN / ALTERNATE.",
        "`agrees` compares table names and disposition counts with the approved answer for that variant",
        "(T6 asserts full equality).",
        "",
        "| Model | Origin | Tables | Unmapped fact types | Foreign keys | Nullable columns | Agrees |",
        "|---|---|---|---|---|---|---|",
    ]
    totals = {v: dict.fromkeys(keys, 0) for v in ("HALPIN", "ALTERNATE")}
    differing = 0
    for row in data:
        if "skipped" in row:
            lines.append(f"| `{row['model']}` | {row['origin']} | skipped: {row['skipped']} | | | | |")
            continue
        cells = []
        for key in keys:
            h, a = row["HALPIN"][key], row["ALTERNATE"][key]
            totals["HALPIN"][key] += h
            totals["ALTERNATE"][key] += a
            cells.append(f"{h} / {a}")
        if row["HALPIN"] != row["ALTERNATE"]:
            differing += 1
        agrees = f"{row['HALPIN'].get('agrees', '')} / {row['ALTERNATE'].get('agrees', '')}" if row["origin"] == "corpus" else ""
        lines.append(f"| `{row['model']}` | {row['origin']} | " + " | ".join(cells) + f" | {agrees} |")
    total = " | ".join(f"{totals['HALPIN'][k]} / {totals['ALTERNATE'][k]}" for k in keys)
    lines += ["", f"**Total** (all mapped models): {total}.", "",
              f"Models whose metrics differ between the variants: {differing} of {sum(1 for r in data if 'skipped' not in r)}."]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    Path(sys.argv[1]).write_text(render(rows()))
