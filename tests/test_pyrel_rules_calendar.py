"""PL14: dates and reference populations in the PyRel rules programs, agreeing with GND's checker.

tests/fixtures/pyrel-rules-calendar/ holds GND's own verdicts (expected.json, generated by
gnd.api.check) for Date and Duration roles, Date ranges, date_add and date_sub in guarded comparisons,
out-of-range dates and GND's 10,000-application limit. Reference populations are checked on the
shipped dispatch and release examples, compared live.
"""
from __future__ import annotations

import json
import shutil
import subprocess
from pathlib import Path

import pytest
from test_pyrel_rules_derivations import _as_verdicts
from test_pyrel_rules_families import NATIVE, _assert_agrees, _ids

from gnd import api
from gnd.export.pyrel_rules import render
from gnd.export.pyrel_runtime import ExportInputError, _parse_document

ROOT = Path(__file__).resolve().parents[1]
CORPUS = ROOT / 'tests/fixtures/pyrel-rules-calendar'
EXAMPLES = ROOT / 'src/gnd/examples'
EXPECTED = json.loads((CORPUS / 'expected.json').read_text())['results']
CASES = sorted(EXPECTED.items())
_STATUS = {'term:date-out-of-range', 'term:temporal-work-limit'}


def _run(program, population):
    return subprocess.run([str(NATIVE), '-I', str(program), str(population)], capture_output=True, text=True,
                          timeout=300, check=False)


def _program(tmp_path_factory, model):
    path = tmp_path_factory.getbasetemp() / f'calendar-{Path(model).stem}.py'
    if not path.exists():
        path.write_text(render(CORPUS / model, 'duckdb'))
    return path


def _reasons(stdout):
    """{rule: reason} for rules the program printed as not checked."""
    return {line.split('  ')[0]: line.split('(', 1)[1].rstrip(')') for line in stdout.splitlines()
            if '  not checked  ' in line}


@pytest.mark.pyrel_oracle
@pytest.mark.parametrize('name,row', CASES, ids=[name for name, _ in CASES])
def test_duckdb_program_agrees_with_gnd_on_dates(tmp_path_factory, name, row):
    run = _run(_program(tmp_path_factory, row['model']), CORPUS / row['population'])
    assert run.stderr == '', run.stderr
    assert run.returncode == row['exit_code'], run.stdout
    _assert_agrees(run.stdout, _as_verdicts(row))
    unchecked = {v['id']: v['reason_code'] for v in row['verdicts'] if v['verdict'] == 'unchecked'}
    assert {k: v for k, v in _reasons(run.stdout).items() if v in _STATUS} == unchecked


def _gnd_rows(model, population):
    gnd = api.check(str(model), str(population), unredacted=True)
    gnd = gnd.get('report', gnd)   # reference-bearing checks wrap the report (schema 12)
    ids = _ids(_parse_document(model.read_text()))
    row = {'verdicts': [dict(v, id=ids[v['constraint_ref']]) for v in gnd['verdicts']],
           'derivations': [{'fact_type': d['derivation_ref'].split(':', 1)[1], 'verdict': d['verdict'],
                            'findings': d.get('findings') or []} for d in gnd.get('derivations') or []]}
    return gnd['exit_code'], row


