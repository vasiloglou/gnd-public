@pytest.mark.pyrel_oracle
def test_a_plan_without_steps_is_a_snapshot_check(tmp_path):
    """The same program checks a single population, as before plans existed."""
    pre = CORPUS / 'attempt-1-prerequisites.pre.json'
    program = tmp_path / 'rules.py'
    program.write_text(render(CORPUS / 'registrar.orm.json', 'duckdb'))
    run = subprocess.run([str(NATIVE), '-I', str(program), str(pre)], capture_output=True, text=True, timeout=300,
                         check=False)
    gnd = api.check(str(CORPUS / 'registrar.orm.json'), str(pre), unredacted=True)
    assert run.returncode == gnd['exit_code'] == 0, run.stdout + run.stderr
    ids = _ids(_parse_document((CORPUS / 'registrar.orm.json').read_text()))
    row = {'verdicts': [dict(v, id=ids[v['constraint_ref']]) for v in gnd['verdicts']],
           'derivations': [{'fact_type': d['derivation_ref'].split(':', 1)[1], 'verdict': d['verdict'],
                            'findings': d.get('findings') or []} for d in gnd.get('derivations') or []]}
    _assert_agrees(run.stdout, _as_verdicts(row))


@pytest.mark.pyrel_oracle
def test_a_long_plan_finishes_in_time(tmp_path):
    """Standing rule 2: 100 steps (enroll, then drop, the same course over and over) in one PyRel model.
    Measured: about 0.35 s per step, so 100 steps take about 36 s; plans are capped at 500 steps."""
    steps = json.loads((CORPUS / 'attempt-3-accepted.steps.json').read_text())
    steps['steps'] = [step for _ in range(50) for step in (
        {'op': 'enroll', 'bindings': {'student': 'maya', 'course': 'PHIL101', 'term': 'spring'}},
        {'op': 'drop', 'bindings': {'student': 'maya', 'course': 'PHIL101', 'term': 'spring'}})]
    path = tmp_path / 'long.steps.json'
    path.write_text(json.dumps(steps))
    program = tmp_path / 'rules.py'
    program.write_text(render(CORPUS / 'registrar.orm.json', 'duckdb'))
    started = time.monotonic()
    run = _run(program, CORPUS / 'attempt-3-accepted.pre.json', path)
    assert time.monotonic() - started < 60, 'a 100-step plan took too long'
    assert run.returncode == 0, run.stdout[-2000:] + run.stderr


