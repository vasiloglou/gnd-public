@pytest.mark.parametrize('change,reason', [
    (lambda d: d['object_types'].append({'id': 'moment', 'name': 'Moment', 'kind': 'value', 'primitive': 'DateTime'})
     or d['fact_types'][0]['roles'].append({'object_type': 'moment', 'role_name': 'moment'}), "'DateTime'"),
    (lambda d: d['constraints'][0]['consequent']['comparison'].update(
        right={'fn': 'date_add', 'args': [{'fn': 'date_add', 'args': ['$last', '$n']}, '$n']}), 'nested date terms'),
    (lambda d: d['constraints'][0]['consequent']['comparison'].update(right={'fn': 'round', 'args': ['$n', 0]}),
     "the function 'round'"),
])
def test_unsupported_calendar_terms_are_refused_by_name(change, reason):
    from gnd.export.pyrel_rules import requirements
    doc = _parse_document((CORPUS / 'clinic.orm.json').read_text())
    change(doc)
    with pytest.raises(ExportInputError, match=reason):
        requirements(doc)


