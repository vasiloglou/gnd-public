"""PL13b: derived fact types in the PyRel rules programs, agreeing with GND's checker.

The corpus in tests/fixtures/pyrel-rules-derivations/ holds GND's own verdicts (expected.json,
generated by gnd.api.check). Each derived head is computed by PyRel `define` rules, and GND's
derivation check becomes two requirements: every computed fact is claimed, and every claimed fact
is computed. The DuckDB program must report what GND reports: the same constraint verdicts, the
same derivation verdicts with the same missing and extra facts, and the same exit code.
"""
from __future__ import annotations

import json
import re
import subprocess
import time
from pathlib import Path

import pytest
from test_pyrel_rules_families import NATIVE, _assert_agrees, _ids

from gnd import api
from gnd.export.pyrel_rules import render, requirements
from gnd.export.pyrel_runtime import ExportInputError, _parse_document

ROOT = Path(__file__).resolve().parents[1]
CORPUS = ROOT / 'tests/fixtures/pyrel-rules-derivations'
EXPECTED = json.loads((CORPUS / 'expected.json').read_text())['results']
CASES = sorted(EXPECTED.items())
_LABEL = {'derived-extension-incomplete': 'missing', 'derived-extension-unsound': 'extra'}


def _program(tmp_path_factory, model):
    path = tmp_path_factory.getbasetemp() / f'derivations-{Path(model).stem}.py'
    if not path.exists():
        path.write_text(render(CORPUS / model, 'duckdb'))
    return path


def _as_verdicts(row):
    """GND's constraint verdicts plus its derivation verdicts, in the shape _assert_agrees reads."""
    verdicts = [(v['id'], v) for v in row['verdicts']]
    for d in row['derivations']:
        witness = [{_LABEL[f['kind']]: f['witness']} for f in d['findings']]
        verdicts.append((f"derivation:{d['fact_type']}",
                         {'verdict': d['verdict'], 'constraint_type': 'derivation', 'offending_facts': witness}))
    return verdicts


@pytest.mark.pyrel_oracle
@pytest.mark.parametrize('name,row', CASES, ids=[name for name, _ in CASES])
def test_duckdb_program_agrees_with_gnd_on_derivations(tmp_path_factory, name, row):
    program = _program(tmp_path_factory, row['model'])
    run = subprocess.run([str(NATIVE), '-I', str(program), str(CORPUS / row['population'])],
                         capture_output=True, text=True, timeout=300, check=False)
    assert run.stderr == '', run.stderr
    assert run.returncode == row['exit_code'], run.stdout
    _assert_agrees(run.stdout, _as_verdicts(row))


