"""PL15: operation plans in the PyRel rules programs, agreeing with GND's plan walk.

tests/fixtures/pyrel-rules-plans/ holds GND's transition reports (expected.json, generated by
gnd.api.transition) for a registrar model with operations: the tutorial bot's three attempts and one plan
per step check. The generated DuckDB program, run with --pre and --steps, must report what GND reports:
for every state, the same rule verdicts and witnesses; for every step, the same failing checks at GND's
locators; and the same exit code.
"""
