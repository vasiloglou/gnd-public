ROOT = Path(__file__).resolve().parents[1]
CORPUS = ROOT / 'tests/fixtures/pyrel-rules-plans'
EXPECTED = json.loads((CORPUS / 'expected.json').read_text())['results']
CASES = sorted(EXPECTED.items())
_STATUS = {'fail': 'violated', 'warning': 'warning', 'unchecked': 'not checked', 'vacuous': 'vacuous'}


def _run(program, pre, steps):
    return subprocess.run([str(NATIVE), '-I', str(program), '--pre', str(pre), '--steps', str(steps)],
                          capture_output=True, text=True, timeout=300, check=False)


def _program(tmp_path_factory, model):
    path = tmp_path_factory.getbasetemp() / f'plans-{Path(model).stem}.py'
    if not path.exists():
        path.write_text(render(model, 'duckdb'))
    return path


def _split(stdout):
    """{state k: its rule lines}, {step k: [(locator, status, witness)]} from a plan report."""
    states, steps = {}, {}
    for line in stdout.splitlines():
        where, _, rest = line.partition('  ')
        kind, k = where.split(' ')
        if kind == 'state':
            states.setdefault(int(k), [])
            if rest != 'every rule holds':
                states[int(k)].append(rest)
        elif rest.startswith('$.steps['):
            locator, status, *witness = rest.split('  ')
            steps.setdefault(int(k), []).append((locator, status, json.loads(witness[0]) if witness and witness[0][0] in '[{"' else None))
    return states, steps


def _snapshot(report, ids):
    """A GND snapshot report in the shape _assert_agrees reads, keeping only what does not pass."""
    if report is None:
        return []
    row = {'verdicts': [dict(v, id=ids[v['constraint_ref']], constraint_type=v.get('constraint_type', ''))
                        for v in report['verdicts'] if v['verdict'] != 'pass'],
           'derivations': [d for d in report.get('derivations') or [] if d['verdict'] != 'pass']}
    return _as_verdicts(row)


def _assert_plan_agrees(stdout, gnd, model):
    ids = _ids(_parse_document(Path(model).read_text()))
    families = {}
    doc = _parse_document(Path(model).read_text())
    for c in doc.get('constraints', []):
        families[c['id']] = c['type']
    for fact in doc['fact_types']:
        for c in fact.get('constraints') or []:
            families[c.get('id')] = c['type']
    states, steps = _split(stdout)
    snapshots = [gnd['pre_snapshot']] + [s['intermediate'] for s in gnd['steps_out']]
    assert sorted(states) == list(range(len(snapshots))), states
    for k, snapshot in enumerate(snapshots):
        verdicts = [(cid, dict(v, constraint_type=families.get(cid, v.get('constraint_type'))))
                    for cid, v in _snapshot(snapshot, ids)]
        if k == 0:   # GND's compiled precondition obligations, judged on the pre-state
            verdicts += [(v['locator'], {'verdict': v['verdict'], 'constraint_type': 'compiled-subset',
                                         'offending_facts': v['offending_facts']})
                         for v in gnd.get('pre_snapshot_verdicts') or [] if v['verdict'] != 'pass']
        _assert_agrees('\n'.join(states[k]), verdicts)
    for step in gnd['steps_out']:
        want = sorted((v['locator'], _STATUS[v['verdict']]) for v in step['verdicts'] if v['verdict'] != 'pass')
        ours = sorted((loc, status) for loc, status, _ in steps.get(step['index'], []))
        assert ours == want, (step['index'], ours, want)
        for v in step['verdicts']:
            if v['kind'] == 'dynamic-rule' and v['verdict'] in ('fail', 'warning'):
                witness = next(w for loc, _, w in steps[step['index']] if loc == v['locator'])
                assert witness == v['offending_facts'], (witness, v['offending_facts'])


@pytest.mark.pyrel_oracle
@pytest.mark.parametrize('name,row', CASES, ids=[name for name, _ in CASES])
def test_duckdb_program_agrees_with_gnd_on_plans(tmp_path_factory, name, row):
    model = CORPUS / row['model']
    run = _run(_program(tmp_path_factory, model), CORPUS / row['pre'], CORPUS / row['steps'])
    assert run.stderr == '', run.stderr
    assert run.returncode == row['exit_code'], run.stdout
    _assert_plan_agrees(run.stdout, row, model)


def _yaml_to_json(path, out):
    from ruamel.yaml import YAML
    out.write_text(json.dumps(YAML(typ='safe').load(path.read_text())))
    return out


@pytest.mark.pyrel_oracle
@pytest.mark.parametrize('plan', ['plan-draft-1', 'plan-draft-2'])
def test_shipped_approvals_plans_agree_with_gnd(tmp_path, plan):
    """The hero animation's example: draft 1 pays before approval; draft 2 approves, submits, then pays."""
    folder = ROOT / 'src/gnd/examples/approvals'
    model, steps = folder / 'model.orm.yaml', folder / f'{plan}.steps.json'
    pre = _yaml_to_json(folder / 'state.pop.yaml', tmp_path / 'state.pop.json')
    program = tmp_path / 'rules.py'
    program.write_text(render(model, 'duckdb'))
    run = _run(program, pre, steps)
    report = api.transition(str(model), str(folder / 'state.pop.yaml'), str(steps), unredacted=True)
    report = report.get('report', report)
    transition = report['transition']
    gnd = {'pre_snapshot': transition['pre_snapshot'], 'pre_snapshot_verdicts': transition.get('pre_snapshot_verdicts'),
           'steps_out': [{'index': s['index'], 'verdicts': s['verdicts'], 'intermediate': s['intermediate']}
                         for s in transition['steps']]}
    assert run.stderr == '', run.stderr
    assert run.returncode == report['exit_code'], run.stdout
    _assert_plan_agrees(run.stdout, gnd, model)


