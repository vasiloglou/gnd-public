def _variant(change):
    """The orders model with one change, parsed but not validated: refusals are tested on the lowering itself."""
    doc = _parse_document((CORPUS / 'orders.orm.json').read_text())
    change({f['id']: f for f in doc['fact_types']})
    return doc


@pytest.mark.parametrize('change,reason', [
    (lambda f: f['order_total']['derivation_rule']['aggregate'].update(fn='avg'), 'uses avg'),
    (lambda f: f['line_cents']['derivation_rule']['head'].update(cents={'fn': 'div', 'args': ['$q', 2]}),
     "uses the function 'div'"),
    (lambda f: f['line_cents']['derivation_rule']['head'].update(cents={'fn': 'mod', 'args': ['$q', 2]}),
     "uses the function 'mod'"),
    (lambda f: f['order_total'].update(derivation='semiderived'), 'semiderived with an aggregate'),
    (lambda f: f['priority'].update(derivation_rule='an order is a priority order when it is big or gold'),
     'opaque'),
])
def test_unsupported_derivations_are_refused_by_name(change, reason):
    with pytest.raises(ExportInputError, match=reason):
        requirements(_variant(change))


@pytest.mark.pyrel_oracle
def test_recursive_derivation_over_a_long_chain_finishes_in_time(tmp_path):
    """Standing rule 2: a 500-edge prerequisite chain. Its 125,250-fact closure is computed in full; the
    semiderived claim is empty, so the first missing fact is reported."""
    edges = [(f'c{i}', f'c{i + 1}') for i in range(500)]
    population = {'population': {'model': 'registrar-semiderived.orm.json',
                                 'model_id': 'urn:gnd:pl13b:registrar-semiderived',
                                 'covers': ['course_needs', 'passed', 'enrolls', 'prerequisite_chain']},
                  'facts': {'course_needs': [{'course': a, 'prerequisite': b} for a, b in edges]}}
    path = tmp_path / 'chain.population.json'
    path.write_text(json.dumps(population))
    program = tmp_path / 'rules.py'
    program.write_text(render(CORPUS / 'registrar-semiderived.orm.json', 'duckdb'))
    started = time.monotonic()
    run = subprocess.run([str(NATIVE), '-I', str(program), str(path)], capture_output=True, text=True,
                         timeout=300, check=False)
    assert time.monotonic() - started < 60, 'a 125,250-fact closure took too long'
    line = next(l for l in run.stdout.splitlines() if l.startswith('derivation:prerequisite_chain  '))
    assert line == 'derivation:prerequisite_chain  violated  [{"missing": {"course": "c0", "prerequisite": "c1"}}]'


