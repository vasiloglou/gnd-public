"""Generate a project OUTSIDE the checkout, and describe what landed.

v5.1 Phase 1 §6.1. The point of generating outside the checkout is that an
outsider's project is not on GND's `sys.path`, does not inherit its pytest
configuration, and cannot import the development tree by accident. A fixture
that generated into `examples/` would prove none of that -- it would measure
GND running its own examples, which is what the milestone's risk register calls
"an outsider in name only".

The generated tree is transient (a `tmp_path`); what the repository commits is
the generator INPUT and a canonical receipt, so a reader can reproduce the tree
without a 12-file blob in git (r2 R3).
"""

from __future__ import annotations

import hashlib
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]


@dataclass(frozen=True)
class GeneratedProject:
    """One generated tree, plus the digests that describe it."""

    root: Path
    package: str
    manifest: dict[str, str]

    @property
    def smoke_module(self) -> Path:
        """The emitted smoke module. Exactly one exists, by construction."""
        modules = sorted(self.root.glob("test_architecture_smoke_*.py"))
        if len(modules) != 1:
            raise AssertionError(
                f"expected exactly one smoke module under {self.root}, found "
                f"{[module.name for module in modules]}"
            )
        return modules[0]

    def is_outside(self, other: Path) -> bool:
        """True when this tree is not inside ``other`` -- T1.1b's assertion."""
        return not self.root.resolve().is_relative_to(other.resolve())


def generate_project(model_path: str, out: Path, *, package: str) -> GeneratedProject:
    """Run the real `gnd codegen` CLI into ``out`` and describe the result.

    The CLI is driven as a SUBPROCESS rather than by importing the emitter: the
    claim under test is that a project generated by the shipped command runs
    somewhere else, and an in-process call would inherit this interpreter's
    `sys.path` -- the very thing the isolation half then has to disprove.

    ``model_path`` is passed through verbatim, repo-relative, because the
    emitted banner and manifest record it exactly as given (IF-P1-4).
    """
    result = subprocess.run(
        [sys.executable, "-m", "gnd", "codegen", model_path, "--out", str(out)],
        cwd=REPO_ROOT,
        check=False,
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        raise AssertionError(
            f"gnd codegen exited {result.returncode} for {model_path}\n"
            f"--- stdout ---\n{result.stdout}\n--- stderr ---\n{result.stderr}"
        )
    manifest = {
        path.relative_to(out).as_posix(): hashlib.sha256(path.read_bytes()).hexdigest()
        for path in sorted(out.rglob("*"))
        if path.is_file()
    }
    return GeneratedProject(root=out, package=package, manifest=manifest)


def declared_test_dependencies(project: GeneratedProject) -> list[str]:
    """What the project's OWN pyproject declares for test time.

    Read from the generated file rather than restated here, so the isolation
    runner installs what the project asks for and a test cannot silently
    disagree with the emitter about what that is (D-P1.2).
    """
    import tomllib

    config = tomllib.loads((project.root / "pyproject.toml").read_text(encoding="utf-8"))
    groups = config.get("dependency-groups", {})
    return list(groups.get("dev", []))


#: What an outsider adds to make the generated skeleton do something: one
#: dependency-free entry point and one smoke row that runs it. `gnd codegen`
#: emits `smoke: []` and no entry point, so a project run straight out of the
#: generator SKIPS every row -- a green that binds nothing. Seeding a real row
#: is what makes "the smoke module runs in the isolated venv" a claim about
#: execution rather than about collection.
_OUTSIDER_ENTRY_POINT = '''"""The outsider's entry point. Standard library only."""

from __future__ import annotations

import sys


def main(argv: list[str]) -> int:
    return 0 if argv[:1] == ["ok"] else 2


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
'''

_OUTSIDER_CONTRACT = """# Created once by gnd codegen; extended by its owner, which is the point.
contract_version: 1
modules: []
artifacts: []
entry_points:
- module: app
  subcommands: []
  flags: []
  consumes: []
  produces: []
  exits: [{code: 0, meaning: accepted}, {code: 2, meaning: usage}]
smoke:
- id: accepts
  entry_point: app
  argv: ["ok"]
  expect_exit: 0
"""


def seed_smoke_row(project: GeneratedProject) -> None:
    """Give the generated project one executable smoke row, as an owner would.

    Both files written here are EXTENSION paths the generator creates once and
    never rewrites, so editing them is the owner's prerogative rather than a
    test reaching past a boundary.
    """
    (project.root / "app.py").write_text(_OUTSIDER_ENTRY_POINT, encoding="utf-8")
    (project.root / "architecture.contract.yaml").write_text(
        _OUTSIDER_CONTRACT, encoding="utf-8"
    )


