def render_doc(doc):
    """Render a parsed (unvalidated) document through the same lowering render() uses."""
    from gnd.export import pyrel_rules
    model = pyrel_rules._Model(doc)
    reqs = pyrel_rules.requirements(doc, model)
    names = pyrel_rules._Names(model)
    return pyrel_rules._derivations(model, names, 'duckdb') and reqs
