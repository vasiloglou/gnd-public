@pytest.mark.pyrel_oracle
def test_reference_covers_are_merged_as_gnd_merges_them(tmp_path):
    """A mandatory rule over a reference-owned fact type is evaluated, not vacuous: GND adds the reference's covers
    to the candidate's. Here every node must start a leg, and DEST-D does not."""
    folder = tmp_path / 'refonly'
    shutil.copytree(CORPUS / 'refonly', folder)
    doc = json.loads((folder / 'model.orm.json').read_text())
    leg = next(f for f in doc['fact_types'] if f['id'] == 'dispatch_leg')
    leg['constraints'] = [{'id': 'every_node_starts_a_leg', 'type': 'mandatory', 'role': 'source', 'source': 'explicit',
                           'status': 'confirmed', 'modality': 'alethic', 'provenance': {'user_quote': 'test'}}]
    (folder / 'model.orm.json').write_text(json.dumps(doc))
    program = tmp_path / 'rules.py'
    program.write_text(render(folder / 'model.orm.json', 'duckdb'))
    run = _run(program, folder / 'seed.pop.json')
    exit_code, row = _gnd_rows(folder / 'model.orm.json', folder / 'seed.pop.json')
    assert run.returncode == exit_code == 1, run.stdout + run.stderr
    _assert_agrees(run.stdout, _as_verdicts(row))
    assert 'every_node_starts_a_leg  violated' in run.stdout


